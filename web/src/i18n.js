export const LANGS = [
  ['en', 'EN'],
  ['fr', 'FR'],
  ['ar', 'ع'],
];

function detect() {
  const q = new URLSearchParams(location.search).get('lang');
  let saved = null;
  try {
    saved = localStorage.getItem('saddsar.lang');
  } catch {
    /* storage may be blocked */
  }
  const l = q || saved || (navigator.language || 'en').slice(0, 2);
  return DICT[l] ? l : 'en';
}

export const lang = detect();
export const locale = { en: 'en-GB', fr: 'fr-FR', ar: 'ar-MA' }[lang];

/** Translate a key, filling {placeholders}. Falls back to English, then the key. */
export function t(key, vars = {}) {
  const s = DICT[lang][key] ?? DICT.en[key] ?? key;
  return s.replace(/\{(\w+)\}/g, (_, k) => (vars[k] ?? `{${k}}`));
}

export function applyDocumentLang() {
  document.documentElement.lang = lang;
  document.documentElement.dir = lang === 'ar' ? 'rtl' : 'ltr';
}

export function setLang(l) {
  try {
    localStorage.setItem('saddsar.lang', l);
  } catch {
    /* ignore */
  }
  const url = new URL(location.href);
  url.searchParams.set('lang', l);
  location.href = url.toString();
}
